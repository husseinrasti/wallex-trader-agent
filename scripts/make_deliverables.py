class DeliverableError(Exception):
    """Bad input: exit 2."""


# ---------------------------------------------------------------- helpers


def _rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT.resolve()).as_posix()
    except ValueError:
        return path.as_posix()


def _resolve(value: str | Path) -> Path:
    p = Path(value)
    if p.is_absolute() or p.exists():
        return p
    return ROOT / p


def _git(*args: str) -> str:
    try:
        out = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, timeout=30, check=False)
    except (OSError, subprocess.SubprocessError):
        return ""
    return out.stdout.strip() if out.returncode == 0 else ""


def _git_state() -> str:
    commit = _git("rev-parse", "--short=12", "HEAD") or "unknown"
    dirty = _git("status", "--porcelain", "--untracked-files=no")
    return f"`{commit}`" + (" (working tree with uncommitted changes)" if dirty else " (clean working tree)")


def secret_fields(settings: Settings) -> dict[str, str]:
    """``{field name: value}`` of every secret setting (``.env``) plus the challenge sub-account id, the
    same set ``wta logs check --secrets`` uses (``Settings.scan_values``). The values are only handed
    to the scanner, never printed."""
    return settings.scan_values()


def _lines(path: Path) -> list[bytes]:
    return [line for line in path.read_bytes().splitlines(keepends=True) if line.strip()]


def _ts(obj: Mapping[str, Any]) -> float | None:
    value = obj.get("ts")
    if isinstance(value, str):
        try:
            return parse_iso(value)
        except ValueError:
            return None
    return None


def _n(value: int) -> str:
    return f"{value:,}"


def _hours(seconds: float) -> str:
    return f"{seconds / 3600.0:.2f} h"


# ---------------------------------------------------------------- the recorded run


def run_facts(log_dir: Path) -> dict[str, Any]:
    """What the README says about the run, all read from its own logs."""
    events = list(iter_family(log_dir, "events"))
    starts = [e for e in events if e.get("kind") == "start"]
    if not starts:
        raise DeliverableError(f"no start event in {log_dir}/events*.jsonl: not an engine log directory")
    start = starts[0]
    data = dict(start.get("data") or {})
    stops = [e for e in events if e.get("kind") == "stop"]
    stop = stops[-1] if stops else None
    decisions = list(iter_family(log_dir, "decisions"))
    kinds: Counter[str] = Counter()
    seen: set[str] = set()
    outcomes = 0
    for rec in decisions:
        if rec.get("kind") == "outcome":
            outcomes += 1
        elif str(rec.get("decision_id")) not in seen:
            seen.add(str(rec.get("decision_id")))
            kinds[str(rec.get("kind"))] += 1
    order_kinds = Counter(str(r.get("strategy")) for r in decisions if r.get("kind") == "order")
    vetoes = sum(1 for r in decisions if r.get("kind") == "veto")
    ai = dict(data.get("ai") or {})
    start_ts = _ts(start) or 0.0
    stop_ts = _ts(stop) if stop else None
    stop_data = dict((stop or {}).get("data") or {})
    return {
        "log_dir": log_dir,
        "mode": str(data.get("mode") or ""),
        "feed": str(data.get("feed") or "live"),
        "synthetic": data.get("feed") == "synthetic" or bool(data.get("synthetic")),
        "exchange": data.get("exchange"),
        "git_commit": str(data.get("git_commit") or ""),
        "git_dirty": data.get("git_dirty"),
        "git_tag": data.get("git_tag"),
        "config_hash": str(data.get("config_hash") or ""),
        "state_db": str(data.get("state_db") or ""),
        "strategies": list(data.get("strategies") or []),
        "watchlist": list(data.get("watchlist") or []),
        "ai_source": ai.get("source"),
        "routes": dict(ai.get("routes") or {}),
        "slow_loop_interval_s": ai.get("slow_loop_interval_s"),
        "reviewer_interval_s": ai.get("reviewer_interval_s"),
        "start": iso(start_ts),
        "start_reason": data.get("reason"),
        "stop": iso(stop_ts) if stop_ts is not None else None,
        "duration_s": (stop_ts - start_ts) if stop_ts is not None else None,
        "ticks": stop_data.get("ticks"),
        "heartbeats": stop_data.get("heartbeats"),
        "processes": len(starts),
        "decisions": sum(kinds.values()),
        "decision_kinds": dict(sorted(kinds.items())),
        "outcome_lines": outcomes,
        "order_strategies": dict(sorted(order_kinds.items())),
        "vetoes": vetoes,
        "event_kinds": dict(sorted(Counter(str(e.get("kind")) for e in events).items())),
    }


def sample_health(log_dir: Path) -> tuple[list[bytes], int]:
    """(the kept heartbeat lines, the number of heartbeats): the first heartbeat of every UTC hour, plus
    the very first and the very last; lines are kept byte for byte, in time order."""
    rows: list[tuple[float, int, bytes]] = []
    for path in family_files(log_dir, "health"):
        for line in _lines(path):
            try:
                obj = json.loads(line)
            except ValueError:
                continue
            ts = _ts(obj) if isinstance(obj, dict) else None
            if ts is not None:
                rows.append((ts, len(rows), line))
    rows.sort()
    if not rows:
        return [], 0
    keep: dict[int, tuple[float, int, bytes]] = {}
    for row in rows:
        keep.setdefault(int(row[0] // 3600), row)
    chosen = {rows[0][1]: rows[0], rows[-1][1]: rows[-1], **{r[1]: r for r in keep.values()}}
    return [r[2] if r[2].endswith(b"\n") else r[2] + b"\n" for r in sorted(chosen.values())], len(rows)


def copy_run(log_dir: Path, dest: Path) -> dict[str, Any]:
    """Write the run folder's data files into ``dest`` (empty). Returns what was written."""
    written: dict[str, Any] = {"families": {}, "skipped": []}
    for base in COPIED_FAMILIES:
        files = family_files(log_dir, base)
        if base == "decisions" and not files:
            raise DeliverableError(f"no decisions*.jsonl in {log_dir}")
        for path in files:
            shutil.copyfile(path, dest / path.name)
            written["families"].setdefault(base, []).append((path.name, len(_lines(path))))
    lines, total = sample_health(log_dir)
    if lines:
        (dest / "health.jsonl").write_bytes(b"".join(lines))
    written["health"] = (len(lines), total)
    journal = log_dir / "journal.md"
    if journal.is_file():
        shutil.copyfile(journal, dest / "journal.md")
    cache = log_dir / "llm_cache"
    entries = tape = 0
    answered: Counter[str] = Counter()
    if cache.is_dir():
        for path in sorted(cache.rglob("*")):
            if path.is_dir() or path.is_symlink():
                continue
            rel = path.relative_to(cache)
            if path.suffix != ".json":
                written["skipped"].append(f"llm_cache/{rel.as_posix()}")
                continue
            target = dest / "llm_cache" / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
            if rel.parts[0] == "mcp_tape":
                tape += 1
            else:
                entries += 1
                answered[_answer_route(path)] += 1
    written["llm_cache"] = (entries, tape)
    written["answered"] = dict(sorted(answered.items()))
    return written


def _answer_route(path: Path) -> str:
    """``provider/model`` of one cached LLM answer (``?`` when the entry does not say)."""
    try:
        req = json.loads(path.read_bytes()).get("request") or {}
    except (ValueError, OSError, AttributeError):
        return "?"
    return f"{req.get('provider') or '?'}/{req.get('model') or '?'}"


# ---------------------------------------------------------------- READMEs


def _find_report(needle: str, pattern: str) -> Path | None:
    """The newest report under docs/REPORTS matching ``pattern`` whose text contains ``needle``."""
    found = []
    for path in (ROOT / "docs" / "REPORTS").glob(pattern):
        try:
            if needle in path.read_text(encoding="utf-8"):
                found.append(path)
        except (OSError, UnicodeDecodeError):
            continue
    return max(found, key=lambda p: (p.stat().st_mtime, p.name)) if found else None


def _routes(facts: Mapping[str, Any]) -> str:
    routes = facts["routes"]
    if not routes:
        return f"AI source `{facts['ai_source']}`"
    parts = [f"{role} `{route}`" for role, route in sorted(routes.items())]
    return f"AI source `{facts['ai_source']}`: " + ", ".join(parts)


def _run_title(name: str, facts: Mapping[str, Any]) -> str:
    feed = "SYNTHETIC feed" if facts["synthetic"] else f"{facts['feed']} feed"
    llm = "real LLM" if facts["ai_source"] == "llm" else f"AI {facts['ai_source']}"
    return f"{facts['mode'].capitalize()} run `{name}` — {feed}, {llm}"


def _kinds_text(kinds: Mapping[str, int]) -> str:
    return ", ".join(f"{n} {k}" for k, n in kinds.items()) or "none"


def run_readme(name: str, facts: Mapping[str, Any], written: Mapping[str, Any], bundle: str | None,
               replay: Mapping[str, Any] | None = None) -> str:
    dur = facts["duration_s"]
    window = f"{facts['start']} → {facts['stop'] or '(no stop event)'}" + (f" ({_hours(dur)})" if dur else "")
    commit = facts["git_commit"]
    clean = {False: "clean tree", True: "uncommitted changes in the tree"}.get(facts["git_dirty"], "tree state unknown")
    health_kept, health_total = written["health"]
    cache_n, tape_n = written["llm_cache"]
    journal_reviews = 0
    synthetic = facts["synthetic"]
    verdict = f" Last result: **{replay['summary']}** ({replay['when']})." if replay else ""
    replay_line = (
        f"Replay: `make replay-deliverable` replays this run from the bundle in "
        f"[`../replay/{name}/`](../replay/{name}/README.md) with no network; its output is in that README.{verdict}"
        if bundle else
        "Replay: these files alone are not enough (the replay also needs the run's state DB); see `docs/REPRODUCE.md`."
    )
    orders = ", ".join(f"{n} {s}" for s, n in facts["order_strategies"].items()) or "none"
    paper = " (paper money)" if facts["exchange"] == "paper" else ""
    answered = written.get("answered") or {}
    answers = ", ".join(f"`{route}` ×{n}" for route, n in answered.items()) or "none"
    llm = (f"AI on, real LLM calls: the {sum(answered.values())} cached answers came from {answers}."
           if facts["ai_source"] == "llm" else f"AI source `{facts['ai_source']}` (no LLM call).")
    silent = sorted({r for r in facts["routes"].values() if not any(a.startswith(str(r).split("/", 1)[0] + "/")
                                                                    for a in answered)})
    silent_note = ""
    if silent and facts["ai_source"] == "llm":
        silent_note = (f" Route(s) that answered no call in this run: {', '.join(f'`{r}`' for r in silent)}"
                       + (" (the Gemini fallback key is quota-limited, HTTP 429)" if any(r.startswith("gemini/")
                                                                                       for r in silent) else "")
                       + ".")
    if facts["mode"] == "live":
        live_line = ("5. A LIVE run on the challenge account, started by the operator after \"go live\" "
                     "(`docs/GO_LIVE_CHECKLIST.md`).")
    else:
        live_line = ("5. Not a live run. No live trading has happened yet: live trading starts only when the operator says "
                     "\"go live\" (`docs/GO_LIVE_CHECKLIST.md`). `api.wallex.ir` is reachable only intermittently "
                     "from the dev machine.")
    metrics = _find_report(f"| log_dir | {_rel(facts['log_dir'])} |", "*/report.md")
    out = [
        f"# {_run_title(name, facts)}",
        "",
        MARKER,
        "",
        "**Summary**",
        f"1. A {_hours(dur) if dur else ''} run of the engine in mode `{facts['mode']}`{paper}, exchange "
        f"`{facts['exchange']}`, strategies {', '.join(facts['strategies'])}. "
        + (f"The feed was the **{SYNTHETIC_NOTE}**. " if synthetic else f"Feed `{facts['feed']}`. ") + llm,
        f"2. Recorded at commit `{commit[:12]}` ({clean}), config hash `{facts['config_hash']}`, "
        f"{window}, {_n(facts['ticks'] or 0)} ticks, {facts['processes']} "
        + ("process (no restart)." if facts["processes"] == 1 else "processes (restarts)."),
        f"3. {facts['decisions']} decisions ({_kinds_text(facts['decision_kinds'])}) and {facts['outcome_lines']} outcome "
        f"lines; orders by strategy: {orders}; vetoes: {facts['vetoes']}. "
        f"{health_kept} of {health_total} heartbeats are kept here (hourly sample).",
        f"4. {replay_line}",
        live_line,
        "",
        "## What this is",
        "",
    ]
    if synthetic:
        ai_text = ("The AI layer was on and called the real LLM: every `kind: plan` record in these files is a real "
                   "model answer." if facts["ai_source"] == "llm" else
                   f"The AI layer ran as `{facts['ai_source']}`, not a real LLM.")
        out += [
            f"> **{SYNTHETIC_NOTE}.** The engine traded paper money on the offline synthetic feed (generated, "
            "deterministic books), because `api.wallex.ir` is reachable only intermittently from the development "
            f"machine. {ai_text}",
            "",
        ]
    out += [
        "| field | value |",
        "| --- | --- |",
        f"| mode / exchange / feed | `{facts['mode']}` / `{facts['exchange']}` / `{facts['feed']}`"
        + (" (SYNTHETIC)" if synthetic else "") + " |",
        f"| AI | {_routes(facts)} |",
        f"| LLM answers in `llm_cache/` | {answers}.{silent_note} |",
        f"| slow loop / reviewer | every {facts['slow_loop_interval_s']} s / every {facts['reviewer_interval_s']} s |",
        f"| strategies | {', '.join(facts['strategies'])} |",
        f"| markets | {len(facts['watchlist'])}: {', '.join(facts['watchlist'])} |",
        f"| recorded commit | `{commit}` ({clean}; "
        + (f"tag `{facts['git_tag']}`" if facts["git_tag"] else "no tag") + ") |",
        f"| config hash | `{facts['config_hash']}` |",
        f"| window (start → stop event) | {window} |",
        f"| ticks / heartbeats / processes | {_n(facts['ticks'] or 0)} / {facts['heartbeats']} / {facts['processes']} "
        f"(start reason `{facts['start_reason']}`) |",
        f"| events | {_kinds_text(facts['event_kinds'])} |",
        f"| source | `{_rel(facts['log_dir'])}` + state DB `{facts['state_db']}` (not in git: `logs/`, `data/` are ignored) |",
        "",
        f"Metrics of this run (equity, drawdown, orders, plans, PNGs): [`{_rel(metrics)}`](../../{_rel(metrics)})."
        if metrics else
        "Metrics of this run: `python -m wta report --source <log dir> --state-db <state DB> --out <dir>`.",
        "",
        "## Files",
        "",
        "| file | lines / entries | content |",
        "| --- | ---: | --- |",
    ]
    describe = {
        "decisions": "decision records (one JSON line each: intent, reason, risk checks, order, plan; "
                     "`kind: outcome` lines point back by `decision_id`). Format: `docs/DECISION_LOG_FORMAT.md`",
        "orders": "order traffic: place / response / cancel / fill lines of the order manager",
        "events": "engine events: start, stop, day_start, ai_degraded / ai_recovered, plan_stale, ...",
    }
    for base in COPIED_FAMILIES:
        for fname, n in written["families"].get(base, []):
            out.append(f"| [`{fname}`]({fname}) | {n} | {describe[base]} |")
    if health_kept:
        where = "all of them are in the bundle" if bundle else "all of them are in the run's own health files"
        out.append(f"| [`health.jsonl`](health.jsonl) | {health_kept} | heartbeats sampled hourly: the first one of each "
                   f"UTC hour + the first and the last, byte for byte (of {health_total}; {where}) |")
    journal = facts["log_dir"] / "journal.md"
    if journal.is_file():
        journal_reviews = sum(1 for line in journal.read_text(encoding="utf-8").splitlines() if line.startswith("## Review"))
        out.append(f"| [`journal.md`](journal.md) | {journal_reviews} reviews | Post-trade Reviewer journal "
                   "(one section per hourly review) |")
    out.append(f"| [`llm_cache/`](llm_cache/) | {cache_n} + {tape_n} | {cache_n} cached LLM answers (`<sha256 key>.json`: "
               f"request, response, usage, latency) + {tape_n} MCP/tool tape entries in `llm_cache/mcp_tape/`; "
               "the replay re-derives every plan from these with 0 provider calls |")
    if written["skipped"]:
        out += ["", f"Not copied (not JSON): {', '.join(f'`{s}`' for s in written['skipped'])}."]
    out += [
        "",
        "## How to check and replay",
        "",
        "```",
        f"python -m wta logs check --dir deliverables/{name} --secrets   # every line validates; secrets scan clean",
    ]
    if bundle:
        out.append(f"make replay-deliverable                                        # = python scripts/replay_check.py "
                   f"--bundle deliverables/replay/{name}")
    out += [
        "```",
        "",
        f"Written by `scripts/make_deliverables.py` at commit {_git_state()}. "
        "The decision, order and event files are byte-for-byte copies of the run's own files.",
        "",
    ]
    return "\n".join(out)


def bundle_readme(name: str, facts: Mapping[str, Any], info: Mapping[str, Mapping[str, Any]],
                  replay: Mapping[str, Any] | None) -> str:
    logs, state = info[BUNDLE_LOGS], info[BUNDLE_STATE]
    if replay is None:
        verdict = "not run yet (`make replay-deliverable`)"
    else:
        verdict = replay["summary"]
    out = [
        f"# Replay bundle `{name}` — " + _run_title(name, facts).split(" — ", 1)[1],
        "",
        MARKER,
        "",
        "**Summary**",
        f"1. Everything needed to replay the recorded run `{name}` without `logs/` or `data/` (both are not in git): "
        f"`{BUNDLE_LOGS}` (the whole log directory, LLM cache included), `{BUNDLE_STATE}` (its state DB) and `{BUNDLE_SUMS}`.",
        f"2. One command: `make replay-deliverable` = `python scripts/replay_check.py --bundle deliverables/replay/{name}`. "
        "It checks SHA256SUMS, unpacks into a temporary directory, replays, compares every decision, then removes it.",
        f"3. Result: **{verdict}**.",
        f"4. The run is mode `{facts['mode']}`, feed `{facts['feed']}`"
        + (f" (**{SYNTHETIC_NOTE}**)" if facts["synthetic"] else "")
        + f", commit `{facts['git_commit'][:12]}`, config hash `{facts['config_hash']}`, {facts['start']} → {facts['stop']}.",
        "5. The replay refuses and counts every internet connection and replaces the LLM providers with counting "
        "sentinels; a pass needs both counters at 0. It proves the code reproduces the decisions, not that the strategy earns.",
        "",
        "## Files",
        "",
        "| file | bytes | sha256 | content |",
        "| --- | ---: | --- | --- |",
        f"| `{BUNDLE_LOGS}` | {_n(logs['bytes'])} | `{logs['sha256']}` | `{_rel(facts['log_dir'])}` as `{name}/` "
        f"({logs.get('members', '?')} members: decisions, orders, events, all heartbeats, journal, `llm_cache/`, `run.out`) |",
        f"| `{BUNDLE_STATE}` | {_n(state['bytes'])} | `{state['sha256']}` | the run's state DB `{facts['state_db']}` "
        f"({_n(state.get('sqlite_bytes', 0))} bytes uncompressed): an online SQLite backup from a read-only connection, "
        "VACUUMed, `journal_mode=DELETE`, every table checked row for row (rowids included) against the source, xz -9 |",
        f"| `{BUNDLE_SUMS}` | | | `sha256sum` format; `shasum -a 256 -c {BUNDLE_SUMS}` or `sha256sum -c {BUNDLE_SUMS}` checks it |",
        "",
        "## By hand",
        "",
        "```",
        f"cd deliverables/replay/{name} && shasum -a 256 -c {BUNDLE_SUMS} && cd -",
        "mkdir -p /tmp/wta-bundle && tar -xJf deliverables/replay/"
        f"{name}/{BUNDLE_LOGS} -C /tmp/wta-bundle",
        f"xz -dc deliverables/replay/{name}/{BUNDLE_STATE} > /tmp/wta-bundle/state.sqlite",
        f"python scripts/replay_check.py --log-dir /tmp/wta-bundle/{name} --state-db /tmp/wta-bundle/state.sqlite "
        "--reports-dir ''",
        "```",
        "",
        "## Replay output",
        "",
    ]
    if replay is None:
        out += ["Not run yet.", ""]
    else:
        out += [
            f"`{replay['command']}`, finished {replay['when']} at commit {replay['commit']}: exit {replay['code']}, "
            f"wall {replay['wall_s']:.0f} s.",
            "",
            "```",
            replay["output"].rstrip("\n"),
            "```",
            "",
        ]
    full = _find_report(f"| recorded log dir | `{_rel(facts['log_dir'])}` |", "replay_*.md")
    out += [
        "What the lines mean: `window` is the replayed tick range and how many recorded plans were re-derived "
        "identically from the LLM cache; `network` counts refused connection attempts and LLM provider calls "
        "(both must be 0); `strict` compares every field of every decision, time stamps included; `end` compares the "
        "final heartbeat (informational)."
        + (f" The full report of the same replay over `logs/`: [`{_rel(full)}`](../../../{_rel(full)})." if full else ""),
        "",
        f"Written by `scripts/make_deliverables.py` at commit {_git_state()}.",
        "",
    ]
    return "\n".join(out)


