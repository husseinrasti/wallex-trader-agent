def _too_big(paths: Iterable[Path]) -> list[str]:
    out = []
    for root in paths:
        for p in [root] if root.is_file() else sorted(root.rglob("*")):
            if p.is_file() and p.stat().st_size >= MAX_FILE_BYTES:
                out.append(f"{p.name}: {p.stat().st_size:,} bytes (limit {MAX_FILE_BYTES:,})")
    return out


def _replace(staged: Path, dest: Path, force: bool) -> None:
    if dest.exists():
        if not (_generated(dest) or force):
            raise DeliverableError(f"{_rel(dest)} exists and was not written by this script (pass --force to replace it)")
        shutil.rmtree(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(staged), str(dest))


def run_replay_check(bundle_rel: str) -> dict[str, Any]:
    cmd = [sys.executable, "scripts/replay_check.py", "--bundle", bundle_rel]
    shown = f"python scripts/replay_check.py --bundle {bundle_rel}"
    t0 = time.monotonic()
    proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, check=False)
    wall = time.monotonic() - t0
    output = proc.stdout + (("\n" + proc.stderr) if proc.stderr.strip() else "")
    result = [line for line in proc.stdout.splitlines() if line.startswith("result:")]
    summary = result[-1].split(":", 1)[1].strip() if result else f"no result line (exit {proc.returncode})"
    return {"command": shown, "code": proc.returncode, "output": output, "summary": summary, "wall_s": wall,
            "when": iso(time.time())[:19].replace("T", " ") + " UTC", "commit": _git_state(),
            "ok": proc.returncode == 0 and summary.endswith("-> PASS")}


def _scan(paths: Sequence[Path], settings: Settings) -> list[str]:
    return scan_for_secrets(list(paths), secret_fields(settings))


def make(args: argparse.Namespace) -> int:
    deliverables = _resolve(args.out)
    report = deliverables / "REPORT.md"
    settings = Settings()
    if not args.index_only:
        log_dir = _resolve(args.run_dir)
        if not log_dir.is_dir():
            raise DeliverableError(f"run directory not found: {args.run_dir}")
        name = args.name or log_dir.name
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", name) or name in ("replay", "REPORT.md"):
            raise DeliverableError(f"bad deliverable name {name!r}")
        for dest in [deliverables / name] + ([deliverables / "replay" / name] if args.bundle else []):
            if dest.exists() and not (_generated(dest) or args.force):
                raise DeliverableError(f"{_rel(dest)} exists and was not written by this script "
                                       "(pass --force to replace it)")
        facts = run_facts(log_dir)
        state_name = args.state_db or facts["state_db"]
        state_db = _resolve(state_name) if state_name else None
        if args.bundle and (state_db is None or not state_db.is_file()):
            raise DeliverableError(f"state DB not found: {state_name or '(none recorded in the start event)'}")
        with tempfile.TemporaryDirectory(prefix="wta-deliver-") as tmp:
            stage = Path(tmp)
            run_stage = stage / name
            run_stage.mkdir()
            written = copy_run(log_dir, run_stage)
            info = None
            bundle_stage = stage / "bundle"
            if args.bundle:
                assert state_db is not None
                print(f"bundle:   packing {_rel(log_dir)} + {_rel(state_db)} (xz -9; the state DB takes a minute)")
                info = make_replay_bundle(log_dir, state_db, bundle_stage)
                (bundle_stage / "README.md").write_text(bundle_readme(name, facts, info, None), encoding="utf-8")
            (run_stage / "README.md").write_text(run_readme(name, facts, written, name if args.bundle else None),
                                                 encoding="utf-8")
            staged = [run_stage] + ([bundle_stage] if args.bundle else [])
            big = _too_big(staged)
            if big:
                print("ABORT: file(s) of 50 MB or more, nothing written to deliverables/:", file=sys.stderr)
                for line in big:
                    print(f"  {line}", file=sys.stderr)
                return 1
            print("secrets:  scanning the staged files (configured secret values + key patterns, archives decompressed)")
            findings = _scan(staged, settings)
            if findings:
                print(f"ABORT: secrets scan: {len(findings)} finding(s); nothing written to deliverables/:",
                      file=sys.stderr)
                for line in findings:
                    print(f"  {line.replace(str(stage), '<staging>')}", file=sys.stderr)
                return 1
            print("secrets:  clean")
            run_dest = deliverables / name
            _replace(run_stage, run_dest, args.force)
            print(f"wrote:    {_rel(run_dest)}/ ({sum(len(v) for v in written['families'].values())} log files, "
                  f"health {written['health'][0]}/{written['health'][1]} heartbeats, "
                  f"llm_cache {written['llm_cache'][0]} + {written['llm_cache'][1]} tape)")
            if args.bundle:
                bundle_dest = deliverables / "replay" / name
                _replace(bundle_stage, bundle_dest, args.force)
                assert info is not None
                for fname in BUNDLE_FILES:
                    print(f"wrote:    {_rel(bundle_dest / fname)} ({info[fname]['bytes']:,} bytes, "
                          f"sha256 {info[fname]['sha256'][:16]}…)")
        code = 0
        if args.bundle and args.replay:
            bundle_rel = _rel(deliverables / "replay" / name)
            print(f"replay:   python scripts/replay_check.py --bundle {bundle_rel} (about 2 minutes)")
            replay = run_replay_check(bundle_rel)
            assert info is not None
            readme = deliverables / "replay" / name / "README.md"
            readme.write_text(bundle_readme(name, facts, info, replay), encoding="utf-8")
            (deliverables / name / "README.md").write_text(run_readme(name, facts, written, name, replay),
                                                           encoding="utf-8")
            print(f"replay:   {replay['summary']} (exit {replay['code']}, {replay['wall_s']:.0f} s); output in {_rel(readme)}")
            if not replay["ok"]:
                print(replay["output"], file=sys.stderr)
                code = 1
        readmes = [deliverables / name / "README.md"] + ([deliverables / "replay" / name / "README.md"]
                                                         if args.bundle else [])
        findings = _scan(readmes, settings)
        if findings:
            print(f"secrets scan of the READMEs: {len(findings)} finding(s):", file=sys.stderr)
            for line in findings:
                print(f"  {line}", file=sys.stderr)
            return 1
    else:
        code = 0
    if report.is_file():
        update_report_index(report)
        bad = broken_links(report)
        if bad:
            print(f"REPORT.md: {len(bad)} broken link(s): {', '.join(bad[:10])}", file=sys.stderr)
            return 1
        print(f"index:    {_rel(report)} 'Deliverables index' updated; every relative link resolves")
    else:
        print(f"index:    {_rel(report)} not found; no index written", file=sys.stderr)
    return code


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="make_deliverables.py", description=__doc__.split("\n\n")[0])
    ap.add_argument("--run-dir", default="logs/shadow_synth_4h", help="the recorded run's log directory")
    ap.add_argument("--name", default=None, help="folder name under deliverables/ (default: the run directory's name)")
    ap.add_argument("--state-db", default=None, help="the run's state DB (default: the one its start event names)")
    ap.add_argument("--out", default="deliverables", help="the deliverables directory (default deliverables)")
    ap.add_argument("--bundle", action="store_true", help="also write the replay bundle deliverables/replay/<name>/")
    ap.add_argument("--replay", action="store_true", help="replay the new bundle and put the output in its README")
    ap.add_argument("--force", action="store_true", help="replace a folder this script did not write")
    ap.add_argument("--index-only", action="store_true", help="only rewrite the index block of deliverables/REPORT.md")
    args = ap.parse_args(argv)
    if args.replay and not args.bundle:
        print("make_deliverables: --replay needs --bundle", file=sys.stderr)
        return 2
    try:
        return make(args)
    except DeliverableError as exc:
        print(f"make_deliverables: {exc}", file=sys.stderr)
        return 2
    except ValueError as exc:  # BundleError, ReplayInputError: unreadable inputs
        print(f"make_deliverables: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
