"""Copy a recorded run into ``deliverables/`` (PRD-06 §4) and pack its replay bundle.

    python scripts/make_deliverables.py --run-dir logs/shadow_synth_4h                    # deliverables/shadow_synth_4h/
    python scripts/make_deliverables.py --run-dir logs/shadow_synth_4h --bundle --replay  # + the bundle (make deliverables)
    python scripts/make_deliverables.py --index-only                                     # only REPORT.md's index

1. Run folder ``deliverables/<name>/``: ``decisions-*.jsonl``, ``orders-*.jsonl`` and ``events-*.jsonl``
   copied byte for byte; ``health.jsonl`` with the heartbeats sampled hourly (the first one of every
   UTC hour, plus the very first and the very last); ``journal.md``; ``llm_cache/`` (every JSON entry,
   the ``mcp_tape/`` included); a ``README.md`` with what the run is (mode, feed, AI routes), the
   recorded commit and config hash, the window and how to replay it.
2. ``--bundle``: ``deliverables/replay/<name>/`` = ``logs.tar.xz`` (the whole log directory),
   ``state.sqlite.xz`` (an online backup of the run's state DB, VACUUMed, xz -9) and ``SHA256SUMS``
   (``wta.replay.runner.make_replay_bundle``) with a ``README.md``. Every file must stay under 50 MB.
3. ``--replay`` (needs ``--bundle``): ``scripts/replay_check.py --bundle`` on the new bundle; its
   output goes into the bundle README. A replay that does not PASS is exit 1.
4. Secrets: everything is written into a temporary staging directory first and scanned there
   (``scan_for_secrets`` with the secret values of ``Settings``, i.e. ``.env``, plus the key patterns;
   compressed files are scanned decompressed). Any finding aborts before anything reaches
   ``deliverables/``; findings name file, line and pattern, never the value.
5. ``deliverables/REPORT.md``: the "Deliverables index" block at its top (between the
   ``deliverables-index`` markers) is rewritten from what is in ``deliverables/``, and every relative
   link of REPORT.md must resolve. ``backtest/report.py`` (``assemble_final_report``) rewrites
   REPORT.md without the block: run ``--index-only`` afterwards.

A run folder or bundle that already exists is replaced only when this script wrote it (its README
carries the marker) or with ``--force``. Exit codes: 0 ok; 1 a secrets finding, a replay that does
not PASS, a file of 50 MB or more, a broken link in REPORT.md; 2 bad input (no run, no state DB,
a folder this script did not write).
"""

