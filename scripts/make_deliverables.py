def _h1(path: Path) -> str:
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                return line[2:].strip()
    except (OSError, UnicodeDecodeError):
        pass
    return ""


def _family_line(path: Path, base: str) -> str:
    day = path.stem.split("-")[-1]
    day = f"{day[:4]}-{day[4:6]}-{day[6:]}" if day.isdigit() and len(day) == 8 else day
    recs = list(iter_family_file(path))
    if base == "decisions":
        kinds = Counter(str(r.get("kind")) for r in recs)
        return f"decision records of {day} (UTC): {len(recs)} lines ({_kinds_text(dict(sorted(kinds.items())))})"
    if base == "orders":
        acts = Counter(str(r.get("action")) for r in recs)
        return f"order log of {day} (UTC): {len(recs)} lines ({_kinds_text(dict(sorted(acts.items())))})"
    kinds = Counter(str(r.get("kind")) for r in recs)
    return f"engine events of {day} (UTC): {_kinds_text(dict(sorted(kinds.items())))}"


def iter_family_file(path: Path) -> Iterable[dict[str, Any]]:
    for line in _lines(path):
        try:
            obj = json.loads(line)
        except ValueError:
            continue
        if isinstance(obj, dict):
            yield obj


def _generated(path: Path) -> bool:
    readme = path / "README.md"
    try:
        return readme.is_file() and MARKER in readme.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def _run_rows(folder: Path, prefix: str) -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = [(f"{prefix}README.md", "what the run is, commit, config hash, window, how to replay")]
    for base in COPIED_FAMILIES:
        for path in family_files(folder, base):
            rows.append((f"{prefix}{path.name}", _family_line(path, base)))
    health = folder / "health.jsonl"
    if health.is_file():
        rows.append((f"{prefix}health.jsonl", f"{len(_lines(health))} heartbeats: the first of each UTC hour + the first "
                                             "and the last (all heartbeats are in the replay bundle)"))
    if (folder / "journal.md").is_file():
        reviews = sum(1 for line in (folder / "journal.md").read_text(encoding="utf-8").splitlines()
                      if line.startswith("## Review"))
        rows.append((f"{prefix}journal.md", f"Post-trade Reviewer journal: {reviews} hourly reviews"))
    cache = folder / "llm_cache"
    if cache.is_dir():
        tape = sum(1 for p in (cache / "mcp_tape").glob("*.json")) if (cache / "mcp_tape").is_dir() else 0
        answers = sum(1 for p in cache.glob("*.json"))
        rows.append((f"{prefix}llm_cache/", f"{answers} cached LLM answers + {tape} MCP/tool tape entries "
                                           "(`mcp_tape/`); the replay reads every plan from here"))
    known = {r[0][len(prefix):] for r in rows}
    for path in sorted(folder.iterdir()):
        name = path.name + ("/" if path.is_dir() else "")
        if name not in known and not path.name.startswith("."):
            rows.append((f"{prefix}{name}", _h1(path) if path.suffix == ".md" else "—"))
    return rows


def _bundle_rows(folder: Path, prefix: str) -> list[tuple[str, str]]:
    describe = {
        "README.md": "what the bundle holds, the checksums, how to replay by hand, and the replay output (PASS/FAIL)",
        BUNDLE_LOGS: "the whole recorded log directory (decisions, orders, events, all heartbeats, journal, "
                     "LLM cache, run.out), tar + xz",
        BUNDLE_STATE: "the run's state DB (ticks, books, candles, balances, fills the replay feeds back), "
                      "SQLite online backup + VACUUM, xz -9",
        BUNDLE_SUMS: "sha256 of the two data files; `replay_check.py --bundle` refuses a bundle that does not match",
    }
    rows = []
    for path in sorted(folder.iterdir(), key=lambda p: (p.name != "README.md", p.name)):
        if path.name.startswith("."):
            continue
        rows.append((f"{prefix}{path.name}" + ("/" if path.is_dir() else ""), describe.get(path.name, "—")))
    return rows


def index_block(deliverables: Path) -> str:
    rows: list[tuple[str, str]] = []
    order = list(KNOWN_TOP)
    top = sorted(deliverables.iterdir(), key=lambda p: (p.is_dir(), p.name == "replay",
                                                        order.index(p.name) if p.name in order else len(order), p.name))
    runs = [_h1(p / "README.md") for p in top if p.is_dir() and _generated(p)]
    for path in top:
        if path.name.startswith("."):
            continue
        if path.is_file():
            rows.append((path.name, KNOWN_TOP.get(path.name) or _h1(path) or "—"))
        elif path.name == "replay":
            rows.append(("replay/", "replay bundles: a recorded run + its state DB, checksummed, "
                                    "for `make replay-deliverable` without `logs/` or `data/`"))
            for sub in sorted(p for p in path.iterdir() if p.is_dir() and not p.name.startswith(".")):
                rows.append((f"replay/{sub.name}/", _h1(sub / "README.md") or "a replay bundle"))
                rows += _bundle_rows(sub, f"replay/{sub.name}/")
        elif path.name == "market":
            rows.append(("market/", "the recorded REAL Wallex market data (order books, trades, 1-minute candles): "
                                    "`make market-db` unpacks it to `data/wta.sqlite` for the real-data reports"))
            known = {
                "README.md": "what is inside (rows and time range per table) and the checksums",
                "SHA256SUMS": "sha256 of the archive; `scripts/market_db.py` refuses an archive that does not match",
                "wta.sqlite.xz": "the recorder's market DB (SQLite online backup + VACUUM, xz -9); account and engine "
                                 "tables empty",
            }
            rows += [(f"market/{name}", text) for name, text in known.items() if (path / name).is_file()]
        elif _generated(path):
            rows.append((f"{path.name}/", _h1(path / "README.md")))
            rows += _run_rows(path, f"{path.name}/")
        else:
            rows.append((f"{path.name}/", _h1(path / "README.md") or "—"))
    lines = [
        INDEX_START,
        "## Deliverables index",
        "",
        "Every folder and file under `deliverables/`, one line each (written by `scripts/make_deliverables.py`; rerun "
        "`python scripts/make_deliverables.py --index-only` after `backtest/report.py` rewrites this file). "
        + _trail_note(runs),
        "",
        "| path | what it is |",
        "| --- | --- |",
    ]
    for rel, text in rows:
        link = rel if not rel.endswith("/") or not (deliverables / rel / "README.md").is_file() else rel + "README.md"
        lines.append(f"| [`{rel}`]({link}) | {text.replace('|', '/')} |")
    lines += ["", INDEX_END]
    return "\n".join(lines)


def _trail_note(titles: Sequence[str]) -> str:
    """One sentence on what kind of decision trail the run folders hold (from their README titles)."""
    if any(t.startswith("Live run") for t in titles):
        return "The live run's decision trail is in its run folder below."
    if not titles:
        return "No run has been copied here yet."
    synthetic = all("SYNTHETIC" in t for t in titles)
    return ("No live trading has happened yet, so there is no live decision log here. The decision trail below "
            + ("comes from runs on the SYNTHETIC feed (generated market data, not evidence of performance)."
               if synthetic else "comes from paper (shadow) runs."))


def update_report_index(report: Path) -> None:
    """Put the index block at the top of REPORT.md (after the title and its first paragraph), or
    replace the block already there."""
    text = report.read_text(encoding="utf-8")
    block = index_block(report.parent)
    if INDEX_START in text and INDEX_END in text:
        head, rest = text.split(INDEX_START, 1)
        _, tail = rest.split(INDEX_END, 1)
        new = head + block + tail
    else:
        lines = text.split("\n")
        at = 0
        if lines and lines[0].startswith("# "):  # after the title and the paragraph under it
            at = 1
            while at < len(lines) and not lines[at].strip():
                at += 1
            while at < len(lines) and lines[at].strip():
                at += 1
        new = "\n".join([*lines[:at], "", block, *lines[at:]])
    report.write_text(new, encoding="utf-8")


LINK = re.compile(r"\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)|src=\"([^\"]+)\"")


def broken_links(report: Path) -> list[str]:
    """Relative links (and image sources) of ``report`` that do not resolve to a file or directory."""
    bad: list[str] = []
    for m in LINK.finditer(report.read_text(encoding="utf-8")):
        target = m.group(1) or m.group(2)
        if re.match(r"[A-Za-z][A-Za-z0-9+.-]*:", target) or target.startswith("#"):
            continue
        path = target.split("#", 1)[0]
        if path and not (report.parent / path).exists():
            bad.append(target)
    return bad


