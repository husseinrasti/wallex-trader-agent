"""The recorded real Wallex market data, shipped in git as ``deliverables/market/``.

    python scripts/market_db.py                  # unpack: check SHA256SUMS, write data/wta.sqlite (never overwrites)
    python scripts/market_db.py --out PATH       # unpack to another file
    python scripts/market_db.py --check          # only check SHA256SUMS and the decompressed tables
    python scripts/market_db.py --pack           # developer: snapshot data/wta.sqlite into the bundle

The bundle is ``wta.sqlite.xz`` (an online backup of the recorder's market DB, VACUUMed, ``xz -9``),
``SHA256SUMS`` (``sha256sum -c SHA256SUMS`` checks it too) and ``README.md`` (what is inside: rows and
time range per table, the checksum of the decompressed file). It holds public market data only: order
books, trades and 1-minute candles recorded from ``api.wallex.ir``, plus the recorder's start/stop
events. ``--pack`` refuses a database with any row in an account or engine table (balances, orders,
fills, positions, equity, plans, kv, engine_*, ticks), so a state DB can never be shipped by mistake.

With the unpacked file the real-data reports of ``docs/REPORTS`` can be rerun offline (the survey,
``bt_books_recorded_*``, ``bt_candles_recorded_ai_off``); ``docs/REPRODUCE.md`` §4.2 lists the commands.

Exit codes: 0 ok; 1 a checksum or table mismatch; 2 bad input (no bundle, the target exists, a
database with account rows for ``--pack``).
"""

from __future__ import annotations

import argparse
import lzma
import os
import shutil
import sqlite3
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

from wta.config import ROOT
from wta.replay.runner import BundleError, read_sha256sums, sha256_file, snapshot_sqlite, sqlite_digest

BUNDLE_DIR = ROOT / "deliverables" / "market"
ARCHIVE = "wta.sqlite.xz"
SUMS = "SHA256SUMS"
README = "README.md"
DEFAULT_DB = ROOT / "data" / "wta.sqlite"
MARKET_TABLES = ("books", "trades", "candles", "events")
# tables that must be empty in a shipped market DB (account or engine state)
PRIVATE_TABLES = ("balances", "orders", "fills", "positions", "equity", "plans", "kv", "engine_books",
                  "engine_candles", "ticks")
_CHUNK = 1 << 20
MARKER = "<!-- generated by scripts/market_db.py --pack: rerun it instead of editing this file -->"


class MarketDBError(RuntimeError):
    """Bad input: no bundle, an existing target, a database that is not market data only."""


def _iso(ts: float | None) -> str:
    if ts is None:
        return "-"
    return datetime.fromtimestamp(float(ts), UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def table_summary(db: Path) -> dict[str, dict[str, object]]:
    """``{table: {"rows": n, "from": iso, "to": iso}}`` of a market DB (read-only)."""
    conn = sqlite3.connect(Path(db).resolve().as_uri() + "?mode=ro", uri=True)
    try:
        names = {r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type = 'table'")}
        out: dict[str, dict[str, object]] = {}
        for name in sorted(names - {"sqlite_sequence"}):
            quoted = '"' + name.replace('"', '""') + '"'
            n = conn.execute(f"SELECT count(*) FROM {quoted}").fetchone()[0]
            cols = {r[1] for r in conn.execute(f"PRAGMA table_info({quoted})")}
            lo = hi = None
            if "ts" in cols and n:
                lo, hi = conn.execute(f"SELECT min(ts), max(ts) FROM {quoted}").fetchone()
            out[name] = {"rows": int(n), "from": _iso(lo), "to": _iso(hi)}
        return out
    finally:
        conn.close()


def _rows(summary: dict[str, dict[str, object]], table: str) -> str:
    return f"{int(summary.get(table, {}).get('rows', 0) or 0):,}"


def _private_rows(summary: dict[str, dict[str, object]]) -> list[str]:
    return [f"{t} ({summary[t]['rows']} rows)" for t in PRIVATE_TABLES if int(summary.get(t, {}).get("rows", 0) or 0)]


def pack(src: Path, bundle: Path) -> dict[str, object]:
    """Snapshot ``src`` (online backup, VACUUM) into ``bundle``: the .xz archive, SHA256SUMS, README."""
    if not src.is_file():
        raise MarketDBError(f"market DB not found: {src}")
    bundle.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="wta-market-") as tmp:
        copy = snapshot_sqlite(src, Path(tmp) / "wta.sqlite")
        summary = table_summary(copy)
        private = _private_rows(summary)
        if private:
            raise MarketDBError(f"{src} is not market data only: {', '.join(private)}")
        raw_sha, raw_bytes = sha256_file(copy), copy.stat().st_size
        part = bundle / (ARCHIVE + ".part")
        with copy.open("rb") as fin, lzma.open(part, "wb", preset=9) as fout:
            shutil.copyfileobj(fin, fout, _CHUNK)
        os.replace(part, bundle / ARCHIVE)
    xz_sha = sha256_file(bundle / ARCHIVE)
    (bundle / SUMS).write_text(f"{xz_sha}  {ARCHIVE}\n", encoding="utf-8")
    rows = "\n".join(
        f"| `{t}` | {s['rows']:,} | {s['from']} | {s['to']} |" for t, s in summary.items() if s["rows"]
    )
    (bundle / README).write_text(
        f"""# Recorded Wallex market data

{MARKER}

**Summary**
1. `{ARCHIVE}` is the recorder's market database `data/wta.sqlite`: **real** order books, trades and 1-minute candles from `api.wallex.ir`, as recorded on the development machine.
2. It holds {_rows(summary, "books")} order-book snapshots and {_rows(summary, "candles")} 1-minute candles (times in the table below). It is short because `api.wallex.ir` answered the development machine only intermittently.
3. It holds public market data only. Account and engine tables are empty (`scripts/market_db.py --pack` refuses anything else).
4. Unpack it with `make market-db` (= `python scripts/market_db.py`): the checksum is verified and `data/wta.sqlite` is written, never overwritten.
5. With it, the real-data reports in `docs/REPORTS` (survey, `bt_books_recorded_*`, `bt_candles_recorded_ai_off`) rerun offline: `docs/REPRODUCE.md` §4.2.

| table | rows | first `ts` (UTC) | last `ts` (UTC) |
|---|---:|---|---|
{rows}

| file | bytes | sha256 |
|---|---:|---|
| `{ARCHIVE}` | {(bundle / ARCHIVE).stat().st_size:,} | `{xz_sha}` |
| `wta.sqlite` (decompressed) | {raw_bytes:,} | `{raw_sha}` |

`sha256sum -c SHA256SUMS` (or `shasum -a 256 -c SHA256SUMS` on macOS) checks the archive by hand. Every
backtest on this file reads it read-only; the report names it `data/wta.sqlite` and says how many hours
of data the window really holds.
""",
        encoding="utf-8",
    )
    return {"sha256": xz_sha, "raw_sha256": raw_sha, "raw_bytes": raw_bytes, "tables": summary}


def verify(bundle: Path) -> str:
    """Check ``bundle/SHA256SUMS`` against the archive; returns the archive's checksum."""
    sums_path = bundle / SUMS
    if not sums_path.is_file():
        raise MarketDBError(f"{sums_path} not found: no market data bundle in {bundle}")
    try:
        sums = read_sha256sums(sums_path)
    except BundleError as exc:
        raise MarketDBError(str(exc)) from None
    if ARCHIVE not in sums:
        raise MarketDBError(f"{SUMS} has no checksum for {ARCHIVE}")
    if not (bundle / ARCHIVE).is_file():
        raise MarketDBError(f"{bundle / ARCHIVE} not found")
    got = sha256_file(bundle / ARCHIVE)
    if got != sums[ARCHIVE]:
        raise ValueError(f"{ARCHIVE}: sha256 {got} does not match {SUMS} ({sums[ARCHIVE]})")
    return got


def unpack(bundle: Path, out: Path) -> dict[str, dict[str, object]]:
    """Verify, then decompress into ``out`` (which must not exist); returns its table summary."""
    verify(bundle)
    if out.exists() or Path(str(out) + "-wal").exists():
        raise MarketDBError(f"{out} exists: move it away first (this never overwrites a market DB)")
    out.parent.mkdir(parents=True, exist_ok=True)
    part = out.with_name(out.name + ".part")
    try:
        with lzma.open(bundle / ARCHIVE, "rb") as fin, part.open("wb") as fout:
            shutil.copyfileobj(fin, fout, _CHUNK)
        sqlite_digest(part)  # a readable SQLite file, every table
        os.replace(part, out)
    finally:
        if part.exists():
            part.unlink()
    return table_summary(out)


def _print_summary(summary: dict[str, dict[str, object]]) -> None:
    for name in MARKET_TABLES:
        if name in summary:
            s = summary[name]
            print(f"  {name:8s} {s['rows']:>7,} rows  {s['from']} -> {s['to']}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Unpack (default), check or pack the recorded Wallex market DB bundle.")
    ap.add_argument("--bundle", type=Path, default=BUNDLE_DIR, help="bundle directory (default deliverables/market)")
    ap.add_argument("--out", type=Path, default=DEFAULT_DB, help="unpack target (default data/wta.sqlite)")
    ap.add_argument("--check", action="store_true", help="only verify SHA256SUMS and that the archive decompresses")
    ap.add_argument("--pack", action="store_true", help="developer: snapshot --db into the bundle")
    ap.add_argument("--db", type=Path, default=DEFAULT_DB, help="the market DB to pack (default data/wta.sqlite)")
    args = ap.parse_args(argv)
    try:
        if args.pack:
            info = pack(args.db, args.bundle)
            print(f"packed {args.db} -> {args.bundle / ARCHIVE} (sha256 {info['sha256']})")
            _print_summary(info["tables"])  # type: ignore[arg-type]
            return 0
        if args.check:
            sha = verify(args.bundle)
            with tempfile.TemporaryDirectory(prefix="wta-market-") as tmp:
                summary = unpack(args.bundle, Path(tmp) / "wta.sqlite")
            print(f"{args.bundle / ARCHIVE}: sha256 {sha} matches {SUMS}; decompresses to a readable SQLite file")
            _print_summary(summary)
            return 0
        summary = unpack(args.bundle, args.out)
        print(f"{args.bundle / ARCHIVE}: SHA256SUMS verified; wrote {args.out} (REAL recorded Wallex market data)")
        _print_summary(summary)
        return 0
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    except (MarketDBError, BundleError, OSError, lzma.LZMAError, sqlite3.DatabaseError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
